/**
 * One dynamic import per language (spec §6.2).
 *
 * `@shikijs/langs` ships 722 grammars; Shiki's own `shiki` entry point pulls a manifest of
 * all of them, which is why this feature uses `createHighlighterCore` and this table
 * instead. Every entry is a **literal** `import()` so Vite can see it: a template literal
 * over a bare specifier is not statically analysable, and would leave an unresolvable
 * `@shikijs/langs/…` in the production bundle. The cost of writing them out is one chunk
 * per language, fetched the first time a file needs it and never before.
 *
 * A grammar module already carries the languages it embeds (`vue` bundles HTML, CSS,
 * TypeScript and the rest), so one entry here is always enough for one file.
 */

