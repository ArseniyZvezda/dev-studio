/**
 * Icon names in a `NodeTypeSchema` are Lucide identifiers supplied by plugin authors.
 *
 * They are resolved through this curated map rather than by importing Lucide's full
 * index and looking the name up dynamically — that would defeat tree-shaking and pull
 * roughly a thousand unused icon components into the bundle. Unknown names fall back to
 * a neutral shape, which is a better failure mode than a blank node header.
 */

import {
  Blocks,
  Box,
  Boxes,
  Braces,
  Brain,
  Circle,
  Cog,
  Code,
  Cpu,
  Database,
  Download,
  Eye,
  FileInput,
  FileOutput,
  FileJson,
  FilePlus,
  FileText,
  Filter,
  FolderSearch,
  FolderSymlink,
  FolderTree,
  FolderUp,
  Globe,
  Grid3x3,
  Hash,
  Image,
  Layers,
  MessageSquare,
  Megaphone,
  Package,
  Play,
  Plus,
  Repeat,
  Shapes,
  Sparkles,
  Tag,
  Terminal,
  Timer,
  Type,
  Upload,
  Wand2,
  type LucideIcon,
} from 'lucide-vue-next'

const ICONS: Record<string, LucideIcon> = {
  blocks: Blocks,
  box: Box,
  boxes: Boxes,
  braces: Braces,
  brain: Brain,
  circle: Circle,
  code: Code,
  cog: Cog,
  cpu: Cpu,
  database: Database,
  download: Download,
  eye: Eye,
  'file-input': FileInput,
  'file-json': FileJson,
  'file-output': FileOutput,
  'file-plus': FilePlus,
  'file-text': FileText,
  filter: Filter,
  'folder-search': FolderSearch,
  'folder-symlink': FolderSymlink,
  'folder-tree': FolderTree,
  'folder-up': FolderUp,
  globe: Globe,
  grid: Grid3x3,
  'grid-3x3': Grid3x3,
  hash: Hash,
  image: Image,
  layers: Layers,
  megaphone: Megaphone,
  'message-square': MessageSquare,
  package: Package,
  play: Play,
  plus: Plus,
  repeat: Repeat,
  shapes: Shapes,
  sparkles: Sparkles,
  tag: Tag,
  terminal: Terminal,
  timer: Timer,
  type: Type,
  upload: Upload,
  wand: Wand2,
  'wand-2': Wand2,
}

export function resolveIcon(name: string | null | undefined): LucideIcon {
  if (!name) return Box
  return ICONS[name.toLowerCase()] ?? Box
}
