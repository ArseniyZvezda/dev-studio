"""Rejected stored identity must fail before init/open writes (VS-102, §5.2.1)."""

from __future__ import annotations

from pathlib import Path
from unittest.mock import AsyncMock, Mock
from uuid import UUID

import httpx
import pytest
from pydantic import ValidationError

from voxarium_studio.core.config import load_config
from voxarium_studio.core.context import AppContext
from voxarium_studio.core.paths import ProjectPaths
from voxarium_studio.core.project import ensure_project, init_project
from voxarium_studio.main import create_app
from voxarium_studio.sync.service import RemoteSync


MARKER = "VS102_SYNTHETIC_REJECTED_CREDENTIAL"
INVALID_CONFIG = (
    "project_name: Rejected\nlanguage: ru\nproject_identity:\n"
    f"  id: valid-id\n  revision: 1\n  token: {MARKER}\n"
)
LAYOUTS = ("no-samples", "config-only", "old-ignore", "legacy")


def _snapshot(root: Path) -> dict:
    """Include empty directories and detect rewrites even when bytes match."""
    return {
        p.relative_to(root).as_posix(): (
            ("file", p.read_bytes(), p.stat().st_mtime_ns) if p.is_file() else ("dir",)
        )
        for p in root.rglob("*")
    }


def _invalid_project(tmp_path: Path, layout: str) -> Path:
    root = tmp_path / "rejected"
    root.mkdir()
    if layout in ("no-samples", "old-ignore"):
        paths = init_project(root, with_samples=False)
    else:
        data = root / ("voxarium_studio" if layout == "legacy" else ".voxarium_studio")
        data.mkdir()
        paths = ProjectPaths.for_inspection(root)
    paths.config_file.write_text(INVALID_CONFIG, encoding="utf-8")
    if layout == "old-ignore":
        paths.gitignore.write_text(
            "# Generated by Voxarium Studio.\napp.db\ncustom/\n", encoding="utf-8",
        )
        paths.plastic_ignore.write_text("# My rules\n/Library\n", encoding="utf-8")
    return root


@pytest.mark.parametrize("layout", LAYOUTS)
@pytest.mark.parametrize("entry", ["init", "ensure"])
@pytest.mark.parametrize("global_exists", [False, True], ids=["no-preferences", "preferences"])
def test_invalid_existing_identity_precedes_all_init_writes(
    tmp_path, studio_home, monkeypatch, layout, entry, global_exists,
):
    root = _invalid_project(tmp_path, layout)
    if global_exists:
        (studio_home / "config.yaml").write_text("language: en\n", encoding="utf-8")
    before, home_before = _snapshot(root), _snapshot(studio_home)
    monkeypatch.setattr(
        "voxarium_studio.core.project.uuid4",
        Mock(side_effect=AssertionError("must not generate identity on rejected read")),
    )
    with pytest.raises(ValidationError):
        (init_project if entry == "init" else ensure_project)(root)
    assert _snapshot(root) == before
    assert _snapshot(studio_home) == home_before


@pytest.mark.parametrize("layout", LAYOUTS)
async def test_bootstrap_lifespan_refuses_before_context_or_registry(
    tmp_path, studio_home, monkeypatch, layout,
):
    root = _invalid_project(tmp_path, layout)
    app = create_app(str(root))
    startup, sync_start = AsyncMock(), AsyncMock()
    monkeypatch.setattr(AppContext, "startup", startup)
    monkeypatch.setattr(RemoteSync, "start", sync_start)
    before, home_before = _snapshot(root), _snapshot(studio_home)
    with pytest.raises(ValidationError):
        async with app.router.lifespan_context(app):
            pytest.fail("invalid bootstrap must not yield")
    assert not hasattr(app.state, "ctx")
    assert not hasattr(app.state, "project_registry")
    startup.assert_not_awaited()
    sync_start.assert_not_awaited()
    assert _snapshot(root) == before
    assert _snapshot(studio_home) == home_before


@pytest.mark.parametrize("layout", LAYOUTS)
@pytest.mark.parametrize("route", ["/api/project/open", "/api/projects/open"])
@pytest.mark.parametrize("global_exists", [False, True], ids=["no-preferences", "preferences"])
async def test_rejected_open_is_safe_and_preserves_incumbent(
    project, tmp_path, studio_home, monkeypatch, caplog, layout, route, global_exists,
):
    root = _invalid_project(tmp_path, layout)
    app = create_app(str(project))
    async with app.router.lifespan_context(app):
        incumbent = app.state.ctx
        # Snapshot after bootstrap; simulate first-open preference migration as well.
        if not global_exists:
            (studio_home / "config.yaml").unlink()
        before, home_before = _snapshot(root), _snapshot(studio_home)
        registries = tuple(dict(getattr(app.state, key)) for key in (
            "project_registry", "project_roots", "project_contexts",
        ))
        browser_bus = app.state.browser_bus
        epoch = app.state.project_epoch
        config_before = incumbent.config.model_dump()
        document = incumbent.paths.docs / "incumbent.md"
        document.write_text("# Still active\n", encoding="utf-8")
        startup, sync_start, sync_reconfigure = AsyncMock(), AsyncMock(), AsyncMock()
        monkeypatch.setattr(AppContext, "startup", startup)
        monkeypatch.setattr(RemoteSync, "start", sync_start)
        monkeypatch.setattr(RemoteSync, "reconfigure", sync_reconfigure)
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://127.0.0.1",
        ) as http:
            response = await http.post(route, json={"path": str(root), "create": False})
            assert response.status_code == 400
            assert response.json() == {"detail": "Invalid project configuration."}
            assert MARKER not in response.text + caplog.text
            assert app.state.ctx is incumbent
            assert app.state.browser_bus is browser_bus
            assert incumbent.bus.forward_to is browser_bus
            assert app.state.project_epoch == epoch
            assert tuple(dict(getattr(app.state, key)) for key in (
                "project_registry", "project_roots", "project_contexts",
            )) == registries
            assert incumbent.config.model_dump() == config_before
            assert document.read_text(encoding="utf-8") == "# Still active\n"
            assert _snapshot(root) == before
            assert _snapshot(studio_home) == home_before
            startup.assert_not_awaited()
            sync_start.assert_not_awaited()
            sync_reconfigure.assert_not_awaited()
            # The incumbent's project-scoped API still resolves after refusal.
            descriptor = next(iter(app.state.project_registry.values()))
            current = await http.get(f"/api/projects/{descriptor.project_id}/project")
            assert current.status_code == 200
            assert Path(current.json()["root"]) == project.resolve()


@pytest.mark.parametrize("identity", [
    "{id: Uppercase, revision: 1}",
    "{id: valid-id, revision: 0}",
    "{id: valid-id, revision: '1'}",
    "{id: valid-id, revision: true}",
    "{id: valid-id}",
    "[valid-id, 1]",
])
def test_other_invalid_identity_shapes_also_precede_init_writes(tmp_path, studio_home, identity):
    root = tmp_path / "invalid-shape"
    paths = ProjectPaths.for_project(root)
    paths.data.mkdir(parents=True)
    paths.config_file.write_text(f"project_identity: {identity}\n", encoding="utf-8")
    before, home_before = _snapshot(root), _snapshot(studio_home)
    with pytest.raises(ValidationError):
        ensure_project(root)
    assert _snapshot(root) == before
    assert _snapshot(studio_home) == home_before


@pytest.mark.parametrize("legacy_config", [False, True], ids=["no-config", "legacy-config"])
@pytest.mark.parametrize("dirname", [".voxarium_studio", "voxarium_studio"])
def test_incomplete_existing_project_never_generates_identity(
    tmp_path, monkeypatch, legacy_config, dirname,
):
    root = tmp_path / "incomplete"
    (root / dirname).mkdir(parents=True)
    paths = ProjectPaths.for_inspection(root)
    if legacy_config:
        paths.config_file.write_text("project_name: Legacy\nlanguage: ru\n", encoding="utf-8")
    monkeypatch.setattr(
        "voxarium_studio.core.project.uuid4",
        Mock(side_effect=AssertionError("legacy read must not generate identity")),
    )
    opened, config = ensure_project(root)
    paths = ProjectPaths.for_project(root)
    assert config.project_identity is None
    assert load_config(opened).project_identity is None
    assert all(p.is_dir() for p in paths.all_dirs)
    assert (paths.pipelines / "prompt-to-voxel-asset.yaml").is_file()
    assert (paths.teams / "default-team.yaml").is_file()


@pytest.mark.parametrize("text", ["project_identity: [unterminated\n", "- not-a-mapping\n"])
def test_existing_yaml_fallback_policy_is_unchanged(tmp_path, text):
    root = tmp_path / "fallback"
    paths = ProjectPaths.for_project(root)
    paths.data.mkdir(parents=True)
    paths.config_file.write_text(text, encoding="utf-8")
    before = paths.config_file.read_bytes()
    _, config = ensure_project(root)
    assert config.project_identity is None
    assert paths.config_file.read_bytes() == before


def test_preflight_respects_existing_global_scope_projection(tmp_path, studio_home):
    root = tmp_path / "obsolete-globals"
    paths = ProjectPaths.for_project(root)
    paths.data.mkdir(parents=True)
    paths.config_file.write_text(
        "project_identity: {id: valid-id, revision: 1}\ntheme: {text_size: 99}\n",
        encoding="utf-8",
    )
    (studio_home / "config.yaml").write_text("language: en\n", encoding="utf-8")
    before, home_before = paths.config_file.read_bytes(), _snapshot(studio_home)
    _, config = ensure_project(root)
    assert config.project_identity.id == "valid-id"
    assert paths.config_file.read_bytes() == before
    assert _snapshot(studio_home) == home_before


@pytest.mark.parametrize("route", ["/api/project/open", "/api/projects/open"])
async def test_valid_existing_open_still_initialises_and_starts(project, tmp_path, route):
    root = tmp_path / "valid"
    root.mkdir()
    paths = init_project(root, with_samples=False)
    identity = load_config(paths).project_identity
    config_before = paths.config_file.read_bytes()
    app = create_app(str(project))
    async with app.router.lifespan_context(app):
        incumbent = app.state.ctx
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://127.0.0.1",
        ) as http:
            response = await http.post(route, json={"path": str(root), "create": False})
        assert response.status_code == 200, response.text
        ctx = app.state.project_roots[root.resolve()].ctx
        assert ctx.config.project_identity == identity
        assert paths.config_file.read_bytes() == config_before
        assert (paths.pipelines / "prompt-to-voxel-asset.yaml").is_file()
        assert (paths.teams / "default-team.yaml").is_file()
        assert ctx._teams_ready
        assert app.state.ctx is (ctx if route == "/api/project/open" else incumbent)


def test_explicit_new_init_generates_and_preserves_identity(tmp_path):
    root = tmp_path / "new"
    root.mkdir()
    paths = init_project(root, with_samples=False)
    identity = load_config(paths).project_identity
    assert identity is not None and UUID(identity.id).version == 4
    assert identity.revision == 1
    config_before = paths.config_file.read_bytes()
    _, opened = ensure_project(root)
    assert opened.project_identity == identity
    assert paths.config_file.read_bytes() == config_before
