def test_init_creates_the_data_directory(project: Path) -> None:
    paths = ProjectPaths.for_project(project)
    assert paths.data.name == "voxarium_studio", "no leading dot, per §5/§14"
    for directory in paths.all_dirs:
        assert directory.is_dir()
    assert paths.gitignore.exists()
    assert paths.plastic_ignore.exists()
    assert paths.config_file.exists()
    assert (paths.data / "temp").is_dir()


def test_gitignore_keeps_the_workflow_but_drops_the_runtime(project: Path) -> None:
    """pipelines/teams/config describe the project's AI workflow and belong in git (§5)."""
    ignored = ProjectPaths.for_project(project).gitignore.read_text(encoding="utf-8")
    rules = ignored.splitlines()
    for runtime in ("app.db-wal", "app.db-shm", "assets/", "runs/", "temp/", "worktrees/"):
        assert runtime in rules
    for committed in ("app.db", "pipelines", "teams", "docs", "skills", "config.yaml"):
        assert committed not in rules


def test_init_upgrades_generated_gitignore_and_preserves_custom_rules(project: Path) -> None:
    paths = ProjectPaths.for_project(project)
    paths.gitignore.write_text(
        "# Generated by Voxarium Studio.\napp.db\napp.db-wal\napp.db-shm\ncustom/\n",
        encoding="utf-8",
    )
    init_project(project)
    upgraded = paths.gitignore.read_text(encoding="utf-8")
    assert upgraded == "# Generated by Voxarium Studio.\napp.db-wal\napp.db-shm\ncustom/\ntemp/\n"
    init_project(project)
    assert paths.gitignore.read_text(encoding="utf-8") == upgraded


