def test_a_config_still_naming_the_preview_limit_loads_and_loses_it(project: Path) -> None:
    """`max_preview_bytes` left the project config on 2026-09-08 — it is the Studio's number.

    Every project written before that carries the key, so it has to be harmless rather than a
    startup failure; and because it is ignored rather than migrated, there is no rule that
    could later override a value somebody chose. `save_config` drops it on the next write.
    """
    paths = ProjectPaths.for_project(project)
    paths.config_file.write_text(
        "explorer:\n  show_data_dir: true\n  max_preview_bytes: 524288\n", encoding="utf-8"
    )
    config = load_config(paths)
    assert config.explorer.show_data_dir is True, "the rest of the section still loads"
    assert not hasattr(config.explorer, "max_preview_bytes")

    save_config(paths, config)
    assert "max_preview_bytes" not in paths.config_file.read_text(encoding="utf-8")


def test_a_project_that_picked_a_look_loads_and_loses_the_key(project: Path) -> None:
    """`look` left the model on 2026-09-16, when every look but Graphite was deleted (§7). A
    project that picked one still loads — keeping the accent and the font the look had applied,
    which were always the project's own fields — and the next save writes the file without it.
    A new project starts on the Graphite design's accent and monospace face."""
    paths = ProjectPaths.for_project(project)
    fresh = AppConfig().theme
    assert (fresh.accent, fresh.mono_font) == ("#a394e8", "jetbrains"), "the Graphite defaults"

    paths.config_file.write_text(
        "theme:\n  mode: light\n  look: material\n  accent: '#6750a4'\n  font: roboto\n",
        encoding="utf-8",
    )
    theme = load_config(paths).theme
    assert (theme.mode, theme.accent, theme.font) == ("light", "#6750a4", "roboto")
    assert not hasattr(theme, "look")

    save_config(paths, load_config(paths))
    assert "\n  look:" not in paths.config_file.read_text(encoding="utf-8")


def test_a_project_written_before_the_looks_loads_and_loses_the_knobs_they_replaced(
    project: Path,
) -> None:
    """`palette`, `surfaces`, `radius`, `density` and `reduce_motion` were folded into the look
    or into `tokens.css` on 2026-09-11. Nothing migrates them — pydantic ignores a key this
    model does not declare, so such a file loads with the rest of its theme intact, and the
    next `save_config` writes the file without them.

    No migration on purpose, for the reason the preview-limit entry already records: an
    upgrade rule needs a marker that stops matching, and "the file names a palette" would go
    on firing for ever over a key that pydantic has already dropped."""
    paths = ProjectPaths.for_project(project)
    paths.config_file.write_text(
        "theme:\n  mode: light\n  palette: warm\n  surfaces: tonal\n  radius: sharp\n"
        "  density: compact\n  reduce_motion: true\n  accent: '#58a6ff'\n  font: inter\n",
        encoding="utf-8",
    )
    theme = load_config(paths).theme
    assert theme.mode == "light", "the file's mode"
    assert (theme.accent, theme.font) == ("#58a6ff", "inter"), "what survived the merge is kept"
    assert not hasattr(theme, "palette")

    save_config(paths, load_config(paths))
    written = paths.config_file.read_text(encoding="utf-8")
    # Indented, so `palette:` does not match the `status_palette:` that is still a field.
    for gone in ("palette", "surfaces", "radius", "density", "reduce_motion"):
        assert f"\n  {gone}:" not in written, gone


