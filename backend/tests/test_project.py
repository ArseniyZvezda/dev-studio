def test_plastic_ignore_is_scoped_and_preserves_existing_rules(project: Path) -> None:
    paths = ProjectPaths.for_project(project)
    assert paths.plastic_ignore == project / "ignore.conf"
    original = paths.plastic_ignore.read_text(encoding="utf-8")
    rules = [line for line in original.splitlines() if not line.startswith("#")]
    assert all(rule.startswith("/voxarium_studio/") for rule in rules)
    assert "/voxarium_studio/app.db" not in rules
    assert "/voxarium_studio/app.db-wal" in rules
    assert "/voxarium_studio/app.db-shm" in rules
    assert "/voxarium_studio/temp" in rules
    assert "/voxarium_studio/plugins/*/.venv" in rules
    paths.plastic_ignore.write_text("# My rules\n/Library\n/voxarium_studio/runs", encoding="utf-8")
    init_project(project)
    updated = paths.plastic_ignore.read_text(encoding="utf-8")
    assert updated.startswith("# My rules\n/Library\n/voxarium_studio/runs\n")
    assert all(rule in updated.splitlines() for rule in rules)
    assert updated.splitlines().count("/voxarium_studio/runs") == 1
    init_project(project)
    assert paths.plastic_ignore.read_text(encoding="utf-8") == updated


def test_init_is_idempotent(project: Path) -> None:
    paths = ProjectPaths.for_project(project)
    sample = next(paths.pipelines.glob("*.yaml"))
    sample.write_text("id: edited\nname: edited\n", encoding="utf-8")
    init_project(project)
    assert sample.read_text(encoding="utf-8").startswith("id: edited")


def test_reinitialising_preserves_existing_database_and_documents(project: Path) -> None:
    from contextlib import closing
    import sqlite3

    paths = ProjectPaths.for_project(project)
    document = paths.docs / "notes.md"
    document.write_text("# Project decisions\n", encoding="utf-8")
    with closing(sqlite3.connect(paths.db_file)) as database:
        database.execute("CREATE TABLE notes (text TEXT)")
        database.execute("INSERT INTO notes VALUES (?)", ("existing task history",))
        database.commit()
    before = paths.db_file.read_bytes()

    assert has_project_data(project)
    assert init_project(project, with_samples=False).data == paths.data
    assert paths.db_file.read_bytes() == before
    assert document.read_text(encoding="utf-8") == "# Project decisions\n"


